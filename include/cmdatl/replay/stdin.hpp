/**
 * @file
 * @brief Bars from standard input (`bars.source=stdin`) for an evaluation: the long CSV layout `bars.source=csv` reads,
 *   a header line then rows, split into paths by `bars.path_column` (a path ends when its cell changes, so a later run
 *   of rows with an earlier cell is a new path); each path is replayed once per parameter set.
 *
 * The reader never blocks past the runner's stop flag: it checks the flag before each step, polls 100 ms at a time,
 * reads at most 64 KiB at once, keeps one unfinished line of at most 1 MiB, and takes only a read of 0 bytes as the
 * end of the stream (a closed pipe can still hold bytes).
 */

namespace cmdatl {
namespace replay {

/** @brief The most bytes read from standard input at once. */
inline constexpr std::size_t STDIN_CHUNK = 64 * 1024;

/** @brief The longest line standard input may send. */
inline constexpr std::size_t STDIN_LINE_MAX = 1024 * 1024;

/** @brief The longest `bars.path_column` cell. */
inline constexpr std::size_t PATH_ID_MAX = 64;

/** @brief Lines from a descriptor, read without waiting more than 100 ms past the stop flag. */
class LineReader {
public:
  /**
   * @brief Reads a descriptor.
   * @param fd The descriptor, left open.
   */
  explicit LineReader(int fd) : fd_(fd), buffer_(STDIN_CHUNK) {}

  /**
   * @brief The next line, without its newline; an unterminated last line is a line too.
   * @param stop The runner's stop flag, checked before every step.
   * @return The line, or none at the end of the stream or once stopped (the flag says which).
   * @throws std::invalid_argument naming `stdin:LINE` for a line over 1 MiB or a failed read.
   */
  std::optional<std::string> next(const std::atomic<bool>& stop) {
#if defined(_WIN32)
    (void)stop;
    throw std::invalid_argument("bars.source = stdin is not supported on this platform");
#else
    while (true) {
      if (stop) {
        return std::nullopt;
      }
      if (at_ < size_) {
        const char* begin = buffer_.data() + at_;
        const auto* newline = static_cast<const char*>(std::memchr(begin, '\n', size_ - at_));
        const auto take = newline != nullptr ? static_cast<std::size_t>(newline - begin) : size_ - at_;
        if (take > STDIN_LINE_MAX - partial_.size()) {
          throw broken("a line longer than 1 MiB");
        }
        partial_.append(begin, take);
        at_ += take + (newline != nullptr ? 1 : 0);
        if (newline != nullptr) {
          return line();
        }
        continue;
      }
      if (ended_) {
        return partial_.empty() ? std::nullopt : std::optional<std::string>(line());
      }
      if (fd_ < 0) {
        throw broken("standard input is not open");
      }
      pollfd ready{fd_, POLLIN, 0};
      const int got = ::poll(&ready, 1, 100);
      if (got == 0 || (got < 0 && errno == EINTR)) {
        continue;
      }
      // macOS answers POLLNVAL for a device it cannot poll (`< /dev/null`): only a closed descriptor is broken.
      if (got < 0 || ((ready.revents & POLLNVAL) != 0 && ::fcntl(fd_, F_GETFD) < 0)) {
        throw broken(got < 0 ? std::strerror(errno) : "standard input is not open");
      }
      const auto n = ::read(fd_, buffer_.data(), buffer_.size());
      if (n < 0 && (errno == EINTR || errno == EAGAIN)) {
        continue;
      }
      if (n < 0) {
        throw broken(std::strerror(errno));
      }
      ended_ = n == 0;
      at_ = 0;
      size_ = static_cast<std::size_t>(n);
    }
#endif
  }

  /**
   * @brief The number of the line `next` returned last, from 1.
   * @return It.
   */
  std::size_t number() const {
    return number_;
  }

private:
  std::string line() {
    ++number_;
    std::string out;
    out.swap(partial_);
    return out;
  }

  std::invalid_argument broken(const std::string& why) const {
    return std::invalid_argument("stdin:" + std::to_string(number_ + 1) + ": " + why);
  }

  int fd_;
  std::vector<char> buffer_;
  std::size_t at_{0};
  std::size_t size_{0};
  std::string partial_;
  std::size_t number_{0};
  bool ended_{false};
};

/**
 * @brief The replays of a grid on each path standard input sends: path `p`, set `g` of `G`, index `p * G + g`.
 *
 * A path is read whole when a worker needs its first replay, under the source's lock, so at most `jobs + 1` paths are
 * in memory. Every path carries the first path's symbols, in its order; the configuration, the instruments and the
 * `data {}` values are the first path's, shared, and only the events are each path's own.
 *
 * @tparam Strategy A strategy generated by `atlc`.
 */
template <typename Strategy>
class StdinSource {
public:
  /**
   * @brief Takes the settings and the grid (cmdatl has refused the keys that name files or the wide layout).
   * @param s The settings, kept by reference.
   * @param grid The grid.
   * @param fd The descriptor the CSV is read from.
   */
  StdinSource(const Settings& s, Grid grid, int fd)
  : s_(s),
    grid_(std::move(grid)),
    sets_(set_count(grid_)),
    reader_(fd),
    symbols_(symbols_of<Strategy>(s)),
    open_point_(s.get_or("bars.open_point", "false") == "true") {
    if (open_point_ && !Strategy::atls_session) {
      throw std::invalid_argument("bars.open_point is for a program with on_open/on_close");
    }
  }

  /**
   * @brief The next replay: the current path's next set, or the first set of the next path read.
   * @param stop The runner's stop flag; the reader returns soon after it is set.
   * @return It, or none at the end of the stream, once stopped, or after a broken stream.
   * @throws std::invalid_argument naming `stdin:LINE` for a broken stream; every later call returns none.
   */
  std::optional<Task> next(const std::atomic<bool>& stop) {
    const std::lock_guard<std::mutex> lock(mutex_);
    if (done_) {
      return std::nullopt;
    }
    try {
      if (!current_ || set_ == sets_) {
        current_.reset();
        current_ = read_path(stop);
        set_ = 0;
      }
      if (!current_) {
        done_ = true;
        return std::nullopt;
      }
      const auto p = paths_ - 1;
      if (p > (std::numeric_limits<std::size_t>::max() - set_) / sets_) {
        throw std::overflow_error("the replays of standard input's paths outnumber an index");
      }
      const auto g = set_++;
      return Task{
        Replay{p * sets_ + g, grid_set(grid_, g), std::nullopt, PathOf{p, std::nullopt, id_, std::nullopt}}, current_,
        nullptr, 0, std::numeric_limits<std::size_t>::max(), std::nullopt
      };
    } catch (...) {
      done_ = true;
      throw;
    }
  }

  /**
   * @brief The paths read so far.
   * @return Their count.
   */
  std::size_t paths() const {
    return paths_;
  }

private:
  std::shared_ptr<const Prepared> read_path(const std::atomic<bool>& stop) {
    if (!cols_) {
      auto header = reader_.next(stop);
      if (!header && stop) {
        return nullptr;
      }
      if (!header) {
        throw std::invalid_argument("stdin:1: no header: standard input is empty");
      }
      trim(*header);
      const auto cells = split_line(*header);
      cols_ = columns_of(s_, cells, "stdin", false);
      if (const auto column = s_.get("bars.path_column")) {
        const auto it = std::find(cells.begin(), cells.end(), *column);
        if (it == cells.end()) {
          throw std::invalid_argument("stdin: no column '" + *column + "' (bars.path_column)");
        }
        path_col_ = static_cast<std::size_t>(it - cells.begin());
      }
    }
    std::vector<BarSeries> series;
    std::optional<std::string> id;
    std::size_t first = 0;
    const auto take = [&](std::vector<std::string> cells, std::size_t number) {
      const auto where = "stdin:" + std::to_string(number);
      if (path_col_) {
        const auto& cell = cells[*path_col_];
        if (cell.empty() || cell.size() > PATH_ID_MAX) {
          throw std::invalid_argument(where + ": a path cell is 1 to 64 bytes");
        }
        if (first != 0 && cell != *id) {
          pending_.emplace(std::move(cells), number);
          return false;
        }
        id = cell;
      }
      first = first == 0 ? number : first;
      if (const auto row = long_row(s_, *cols_, cells, where)) {
        const auto symbol = cols_->symbol_ ? cells[*cols_->symbol_] : s_.need("bars.symbol");
        auto it = std::find_if(series.begin(), series.end(), [&symbol](const BarSeries& x) {
          return x.symbol_ == symbol;
        });
        if (it == series.end()) {
          series.push_back(BarSeries{symbol, interval_of(s_.get_or("bars.interval", "1d")), atl::BarStamp::CLOSE, {}});
          it = series.end() - 1;
        }
        append_bar(*it, *row, where);
      }
      return true;
    };
    bool more = true;
    if (pending_) {
      auto row = std::move(*pending_);
      pending_.reset();
      more = take(std::move(row.first), row.second);
    }
    while (more) {
      auto line = reader_.next(stop);
      if (!line) {
        if (stop) {
          return nullptr;
        }
        break;
      }
      trim(*line);
      if (!line->empty()) {
        more = take(cells_of(*line, cols_->width_, "stdin:" + std::to_string(reader_.number())), reader_.number());
      }
    }
    if (first == 0 && paths_ > 0) {
      return nullptr;
    }
    if (first == 0) {
      throw std::invalid_argument("stdin: no path: standard input holds no row");
    }
    const auto where = "stdin:" + std::to_string(first) + ": the path from here";
    std::vector<std::string> raw;
    for (const auto& x : series) {
      raw.push_back(x.symbol_);
    }
    std::sort(raw.begin(), raw.end());
    if (raw.empty()) {
      throw std::invalid_argument(where + " has no bar (replay.from and replay.to filter each path)");
    }
    if (paths_ == std::numeric_limits<std::size_t>::max()) {
      throw std::overflow_error("standard input's paths outnumber a count");
    }
    std::shared_ptr<const Prepared> out;
    if (!base_) {
      auto prepared = prepare_data<Strategy>(s_, data_of(std::move(series), symbols_), open_point_);
      auto events = std::move(prepared.events_);
      prepared.events_.clear();
      base_ = prepared;
      prepared.events_ = std::move(events);
      first_raw_ = std::move(raw);
      out = std::make_shared<const Prepared>(std::move(prepared));
    } else if (raw != first_raw_) {
      throw std::invalid_argument(where + " carries other symbols than the first path");
    } else {
      auto prepared = *base_;
      const auto order = symbols_.empty() ? base_->symbols_ : symbols_;
      prepared.events_ = bar_events(data_of(std::move(series), order), prepared.market_, open_point_);
      out = std::make_shared<const Prepared>(std::move(prepared));
    }
    ++paths_;
    id_ = std::move(id);
    return out;
  }

  const Settings& s_;
  Grid grid_;
  std::size_t sets_;
  LineReader reader_;
  std::vector<std::string> symbols_;
  bool open_point_;
  std::mutex mutex_;
  bool done_{false};
  std::optional<LongColumns> cols_;
  std::optional<std::size_t> path_col_;
  std::optional<std::pair<std::vector<std::string>, std::size_t>> pending_;
  std::optional<Prepared> base_;
  std::vector<std::string> first_raw_;
  std::shared_ptr<const Prepared> current_;
  std::size_t set_{0};
  std::size_t paths_{0};
  std::optional<std::string> id_;
};

} // namespace replay
} // namespace cmdatl
