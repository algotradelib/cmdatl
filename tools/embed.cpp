// Writes the header that carries the run driver's sources inside cmdatl: each file as an array of string literals of at
// most 16 KiB, every byte that is not plain printable ASCII (and every quote, backslash and question mark) written as a
// three-digit octal escape, so any bytes survive and no literal outgrows a compiler's limit.
//
// Usage: embed OUTPUT NAME=SOURCE...
// NAME is the file's path in the driver's source directory; SOURCE is the file to read.

#include <cstddef>
#include <cstdio>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>
#include <vector>

namespace {

/** @brief The most bytes of one literal. */
constexpr std::size_t CHUNK = 16 * 1024;

/**
 * @brief One byte as it goes inside a literal.
 * @param byte The byte.
 * @return Its spelling.
 */
std::string spelled(unsigned char byte) {
  if (byte >= 0x20 && byte < 0x7f && byte != '"' && byte != '\\' && byte != '?') {
    return std::string(1, static_cast<char>(byte));
  }
  char text[8];
  std::snprintf(text, sizeof text, "\\%03o", byte);
  return text;
}

/**
 * @brief A text as a C++ literal.
 * @param text The text.
 * @return The literal, quotes included.
 */
std::string literal(const std::string& text) {
  std::string out = "\"";
  for (const char c : text) {
    out += spelled(static_cast<unsigned char>(c));
  }
  return out + "\"";
}

}  // namespace

/**
 * @brief Writes the header.
 * @param argc The count.
 * @param argv The output, then `NAME=SOURCE` pairs.
 * @return 0, or 1 when a file cannot be read or written.
 */
int main(int argc, char** argv) {
  if (argc < 2) {
    std::cerr << "usage: embed OUTPUT NAME=SOURCE...\n";
    return 1;
  }
  std::ostringstream out;
  out << "#pragma once\n\n"
      << "// Generated by tools/embed.cpp at build time; edit the sources, not this file.\n\n"
      << "#include <cstddef>\n\n"
      << "namespace cmdatl {\n\n"
      << "/** @brief One file of the run driver's sources: its path in the driver's source directory and its bytes. */\n"
      << "struct DriverFile {\n"
      << "  /** @brief The path, relative to the driver's source directory. */\n"
      << "  const char* path_;\n"
      << "  /** @brief The bytes, in pieces of at most 16 KiB. */\n"
      << "  const char* const* chunks_;\n"
      << "  /** @brief The pieces' sizes. */\n"
      << "  const std::size_t* sizes_;\n"
      << "  /** @brief How many pieces. */\n"
      << "  std::size_t count_;\n"
      << "};\n\n";
  std::vector<std::string> names;
  for (int i = 2; i < argc; ++i) {
    const std::string pair = argv[i];
    const auto eq = pair.find('=');
    if (eq == std::string::npos || eq == 0) {
      std::cerr << "embed: expected NAME=SOURCE, got " << pair << "\n";
      return 1;
    }
    std::ifstream in(pair.substr(eq + 1), std::ios::binary);
    if (!in) {
      std::cerr << "embed: cannot read " << pair.substr(eq + 1) << "\n";
      return 1;
    }
    std::ostringstream bytes;
    bytes << in.rdbuf();
    const auto text = bytes.str();
    const auto index = std::to_string(names.size());
    out << "inline const char* const DRIVER_FILE_" << index << "[] = {\n";
    std::ostringstream sizes;
    std::size_t count = 0;
    for (std::size_t at = 0; at < text.size() || count == 0; at += CHUNK) {
      const auto piece = text.substr(at, CHUNK);
      out << "  " << literal(piece) << ",\n";
      sizes << "  " << piece.size() << ",\n";
      ++count;
      if (text.empty()) {
        break;
      }
    }
    out << "};\n";
    out << "inline const std::size_t DRIVER_SIZES_" << index << "[] = {\n" << sizes.str() << "};\n\n";
    names.push_back(literal(pair.substr(0, eq)) + ", DRIVER_FILE_" + index + ", DRIVER_SIZES_" + index + ", " + std::to_string(count));
  }
  out << "/** @brief Every file of the run driver's sources. */\n"
      << "inline const DriverFile DRIVER_FILES[] = {\n";
  for (const auto& name : names) {
    out << "  {" << name << "},\n";
  }
  out << "};\n\n}  // namespace cmdatl\n";
  std::ofstream file(argv[1], std::ios::binary | std::ios::trunc);
  file << out.str();
  return file ? 0 : 1;
}
